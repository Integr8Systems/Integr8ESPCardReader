"""Integr8 Reader Setup: Windows BLE PIN pairing + MQTT commissioning.

Requirements:
    Windows 10/11, Python 3.10+, Bluetooth LE adapter
    py -m pip install -U bleak

Uses the WinRT custom pairing API for PROVIDE_PIN. Bleak's Windows
pair=True path supports Just Works, which is incompatible with our
ESP32's encrypted/MITM passkey-required configuration characteristic.

No MQTT passwords or Bluetooth PINs are written to disk.
"""
import asyncio
import json
import logging
import queue
import re
import threading
import tkinter as tk
from tkinter import messagebox, ttk

try:
    from bleak import BleakClient, BleakScanner
    from winrt.windows.devices.bluetooth import BluetoothLEDevice
    from winrt.windows.devices.enumeration import (
        DeviceInformation,
        DevicePairingKinds,
        DevicePairingProtectionLevel,
        DevicePairingResultStatus,
    )
except ImportError as exc:
    raise SystemExit("Missing Bleak/WinRT dependencies. Run: py -m pip install -U bleak") from exc

SERVICE_UUID = "875d0000-e1a7-4dca-9a63-a18b1122c001"
WRITE_UUID = "875d0001-e1a7-4dca-9a63-a18b1122c001"
STATUS_UUID = "875d0002-e1a7-4dca-9a63-a18b1122c001"
MAX_CONFIG_BYTES = 512
CHUNK_SIZE = 16


def validate(host, port, device_id, username, password):
    if not host or len(host.encode("utf-8")) >= 96:
        raise ValueError("MQTT server must have 1-95 characters.")
    if any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.-_:" for c in host):
        raise ValueError("MQTT server must be a hostname or IPv4 address.")
    if not port.isdecimal() or not 1 <= int(port) <= 65535:
        raise ValueError("MQTT port must be between 1 and 65535.")
    if not device_id or len(device_id.encode("utf-8")) >= 48:
        raise ValueError("Device ID must have 1-47 characters.")
    if any(c not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_" for c in device_id):
        raise ValueError("Device ID must contain only letters, digits, - and _.")
    if len(username.encode("utf-8")) >= 64 or len(password.encode("utf-8")) >= 96:
        raise ValueError("Username or password is too long.")
    if "\r" in username + password or "\n" in username + password:
        raise ValueError("Username and password must not contain newlines.")
    raw = json.dumps(
        {"host": host, "port": int(port), "deviceId": device_id,
         "username": username, "password": password},
        separators=(",", ":"), ensure_ascii=False,
    ).encode("utf-8")
    if len(raw) > MAX_CONFIG_BYTES:
        raise ValueError("BLE configuration is longer than 512 bytes.")
    return raw


async def pin_pair(address, pin):
    """Windows CustomPairing PROVIDE_PIN, not Bleak pair=True.

    The 6-digit per-device PIN is generated by the reader, viewable in its
    USB serial console or on its provisioning label.
    """
    if not re.fullmatch(r"[0-9]{6}", pin):
        raise ValueError("Enter the reader's six-digit setup PIN.")

    raw_address = int(address.replace(":", "").replace("-", ""), 16)
    requester = await BluetoothLEDevice.from_bluetooth_address_async(raw_address)
    if requester is None:
        raise RuntimeError("Windows cannot resolve the BLE device. Press Scan and try again.")

    try:
        info = await DeviceInformation.create_from_id_async(requester.device_information.id)
        if info.pairing.is_paired:
            return "Reader already paired with Windows."

        if not info.pairing.can_pair:
            raise RuntimeError("Windows reports the reader cannot be paired.")

        custom = info.pairing.custom
        observed = []

        def on_request(sender, args):
            try:
                if args.pairing_kind == DevicePairingKinds.PROVIDE_PIN:
                    args.accept(pin)
                    observed.append("PIN provided")
                elif args.pairing_kind == DevicePairingKinds.CONFIRM_ONLY:
                    # Some Windows stacks ask for a confirmation first.
                    args.accept()
                    observed.append("Pairing confirmed")
                else:
                    observed.append(f"Unsupported pairing ceremony: {args.pairing_kind}")
            except Exception as exc:
                observed.append(f"Pairing callback error: {type(exc).__name__}: {exc}")

        token = custom.add_pairing_requested(on_request)
        try:
            kinds = DevicePairingKinds.PROVIDE_PIN | DevicePairingKinds.CONFIRM_ONLY
            result = await asyncio.wait_for(
                custom.pair_with_protection_level_async(
                    kinds, DevicePairingProtectionLevel.ENCRYPTION_AND_AUTHENTICATION
                ), timeout=45
            )
        finally:
            custom.remove_pairing_requested(token)

        if result.status not in (
            DevicePairingResultStatus.PAIRED,
            DevicePairingResultStatus.ALREADY_PAIRED,
        ):
            extra = "; ".join(observed)
            raise RuntimeError(
                f"Windows PIN pairing failed: {result.status.name}. "
                f"{extra}. Check the PIN and reopen the reader setup window."
            )
        return "Windows paired with authenticated BLE PIN."
    finally:
        requester.close()


async def connect_reader(device):
    """Use the existing bond instead of Bleak's incompatible pair=True."""
    client = BleakClient(
        device, pair=False, timeout=35,
        winrt={"use_cached_services": False},
    )
    await client.connect()
    return client


async def discover_reader(address, timeout=12):
    """Use a fresh BLEDevice object from this asyncio loop."""
    device = await BleakScanner.find_device_by_address(address, timeout=timeout)
    if device is None:
        raise RuntimeError("Reader is not advertising now. Hold BOOT for 4 seconds and Scan again.")
    return device


async def verify_gatt(device):
    client = await connect_reader(device)
    try:
        services = [str(s.uuid).lower() for s in client.services]
        if SERVICE_UUID not in services:
            raise RuntimeError("BLE connected, but Integr8 configuration service was not found.")
        result = await client.read_gatt_char(STATUS_UUID, use_cached=False)
        return bytes(result).decode("ascii", errors="replace")
    finally:
        await client.disconnect()


async def apply_settings(device, payload):
    client = await connect_reader(device)
    try:
        if SERVICE_UUID not in [str(s.uuid).lower() for s in client.services]:
            raise RuntimeError("Integr8 configuration GATT service was not found.")
        await client.write_gatt_char(WRITE_UUID, b"\x01", response=True)
        for start in range(0, len(payload), CHUNK_SIZE):
            part = b"\x02" + payload[start:start + CHUNK_SIZE]
            await client.write_gatt_char(WRITE_UUID, part, response=True)
        await client.write_gatt_char(WRITE_UUID, b"\x03", response=True)

        # ATT write response does not imply NVS save completion.
        for _ in range(20):
            await asyncio.sleep(0.25)
            result = await client.read_gatt_char(STATUS_UUID, use_cached=False)
            status = bytes(result).decode("ascii", errors="replace")
            if status == "SAVED":
                return "MQTT settings saved to the reader. It will reboot."
            if status.startswith("ERROR:"):
                raise RuntimeError(f"Firmware rejected configuration: {status}")
        raise TimeoutError("No saved confirmation received. Check the device serial output.")
    finally:
        try:
            await client.disconnect()
        except Exception:
            pass


class SetupApp:
    def __init__(self, root):
        self.root = root
        root.title("Integr8 Reader Setup")
        root.geometry("525x585")
        root.resizable(False, False)
        self.events = queue.Queue()
        self.devices = {}
        self.busy = False

        frame = ttk.Frame(root, padding=18)
        frame.pack(fill="both", expand=True)
        ttk.Label(frame, text="Integr8 Reader Setup", font=("Segoe UI", 16, "bold")).pack(anchor="w")
        ttk.Label(
            frame, text="BLE discovery, PIN pairing and site MQTT configuration"
        ).pack(anchor="w", pady=(1, 12))

        ttk.Label(frame, text="Nearby reader").pack(anchor="w")
        row = ttk.Frame(frame)
        row.pack(fill="x")
        self.device_select = ttk.Combobox(row, state="readonly", width=47)
        self.device_select.pack(side="left", fill="x", expand=True, padx=(0, 6))
        self.scan_button = ttk.Button(row, text="Scan", command=self.scan)
        self.scan_button.pack(side="right")

        ttk.Label(frame, text="Device-specific Bluetooth pairing PIN (6 digits)").pack(anchor="w", pady=(10, 2))
        self.pin_entry = ttk.Entry(frame, show="*", width=20)
        self.pin_entry.pack(fill="x")
        self.pair_button = ttk.Button(frame, text="1. Pair & Test Bluetooth", command=self.pair)
        self.pair_button.pack(fill="x", pady=(7, 4))

        self.fields = {}
        for title, key, initial in [
            ("MQTT server / IP", "host", ""),
            ("MQTT port", "port", "1889"),
            ("Device ID", "deviceId", ""),
            ("MQTT username", "username", ""),
            ("MQTT password", "password", ""),
        ]:
            ttk.Label(frame, text=title).pack(anchor="w", pady=(7, 2))
            entry = ttk.Entry(frame, show="*" if key == "password" else "")
            entry.insert(0, initial)
            entry.pack(fill="x")
            self.fields[key] = entry

        self.save_button = ttk.Button(frame, text="2. Save MQTT settings to reader", command=self.save)
        self.save_button.pack(fill="x", pady=(13, 2))
        self.status = tk.StringVar(
            value="Hold BOOT for 4 seconds on a running reader, then Scan."
        )
        ttk.Label(frame, textvariable=self.status, wraplength=480).pack(anchor="w", pady=(9, 0))
        root.after(150, self.pump)

    def busy_state(self, busy):
        self.busy = busy
        for control in (self.scan_button, self.pair_button, self.save_button):
            control.configure(state="disabled" if busy else "normal")

    def launch(self, name, coroutine):
        if self.busy:
            return
        self.busy_state(True)
        self.status.set(name + "...")
        def worker():
            try:
                value = asyncio.run(coroutine())
                self.events.put(("ok", name, value))
            except Exception as exc:
                logging.exception("%s failed", name)
                self.events.put(("error", name, f"{type(exc).__name__}: {exc}"))
        threading.Thread(target=worker, daemon=True).start()

    def selected(self):
        entry = self.device_select.get()
        address = self.devices.get(entry)
        if address is None:
            messagebox.showwarning("Select reader", "Scan and select a nearby Integr8 reader.")
            return None
        return address

    def scan(self):
        async def work():
            found = {}
            # Several short scans are more reliable when name is in
            # primary advertisement but Windows misses an early event.
            for _ in range(2):
                observations = await BleakScanner.discover(timeout=6, return_adv=True)
                for address, value in observations.items():
                    device, adv = value
                    name = (adv.local_name or device.name or "").strip()
                    if name.startswith("I8R-") or SERVICE_UUID in (
                        s.lower() for s in adv.service_uuids
                    ):
                        label = f"{name or 'Integr8 Reader'} ({device.address})"
                        found[label] = device.address
                if found:
                    break
            return found
        self.launch("Scanning", work)

    def pair(self):
        address = self.selected()
        if not address:
            return
        pin = self.pin_entry.get().strip()
        if not re.fullmatch(r"\d{6}", pin):
            messagebox.showwarning("PIN required", "Enter the six-digit PIN from the reader.")
            return

        async def work():
            device = await discover_reader(address)
            result = await pin_pair(device.address, pin)
            tested = await verify_gatt(device)
            return f"{result} GATT status: {tested}."
        self.launch("Pairing and testing", work)

    def save(self):
        address = self.selected()
        if not address:
            return
        try:
            payload = validate(
                self.fields["host"].get().strip(),
                self.fields["port"].get().strip(),
                self.fields["deviceId"].get().strip(),
                self.fields["username"].get(),
                self.fields["password"].get(),
            )
        except ValueError as exc:
            messagebox.showerror("MQTT configuration", str(exc))
            return
        if not messagebox.askokcancel(
            "Apply MQTT settings",
            "Save site settings to this reader? It will restart after saving.",
        ):
            return

        async def work():
            device = await discover_reader(address)
            return await apply_settings(device, payload)
        self.launch("Saving settings", work)

    def pump(self):
        while True:
            try:
                kind, action, value = self.events.get_nowait()
            except queue.Empty:
                break
            self.busy_state(False)
            if kind == "error":
                self.status.set(action + " failed: " + value)
                messagebox.showerror("Integr8 Reader Setup", value)
            elif action == "Scanning":
                self.devices = value
                self.device_select.configure(values=list(value))
                self.device_select.set("")
                if value:
                    self.device_select.current(0)
                self.status.set(f"Found {len(value)} Integr8 reader(s).")
            else:
                self.status.set(value)
                if action == "Saving settings":
                    messagebox.showinfo("Integr8 Reader Setup", value)
        self.root.after(150, self.pump)


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    root = tk.Tk()
    SetupApp(root)
    root.mainloop()
